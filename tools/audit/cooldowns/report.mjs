// Markdown tables for docs/audit/cooldowns.md from the summaries (analyze.mjs) and the comparison (compare.mjs).
//   node tools/audit/cooldowns/report.mjs summary-today.json compare.json > tables.md
import { readFileSync } from 'node:fs';
globalThis.location = { search: '?x' };
globalThis.localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
const { HEROES } = await import(new URL('../../../js/heroes.js', import.meta.url).href);
const [sumF, cmpF] = process.argv.slice(2);
const { rows, fights } = JSON.parse(readFileSync(sumF, 'utf8'));
const cmp = cmpF ? JSON.parse(readFileSync(cmpF, 'utf8')) : [];
const f1 = (x) => (x == null ? '-' : x.toFixed(1)), pc = (x) => (x == null ? '-' : Math.round(100 * x) + '%');
const KIND = { state: 'on him', ally: 'on a friend', summon: 'summon/pet', zone: 'in the world', foe: 'on an enemy' };
const name = (h) => `${HEROES[h].name} (${h})`, abn = (h, ab) => `${HEROES[h].abilities.find((a) => a.id === ab).name} (${ab})`;
const what = (r) => Object.keys(r.keys).slice(0, 3).join(', ');
const cell = (r) => (r ? `${f1(r.cd)} / ${f1(r.dur)} / ${f1(r.cdLeft)} / ${pc(r.ready)} / **${pc(r.uptime)}**` : '-');
// one line per ability and kind of lasting thing, its three tiers side by side
const groups = {};
for (const r of rows) { if (r.casts < 5) continue; const k = r.hero + '|' + r.ab + '|' + r.cls; (groups[k] || (groups[k] = {}))[r.tier] = r; }
const lasting = Object.entries(groups).filter(([, g]) => Object.values(g).some((r) => (r.durRaw ?? 0) >= 1.5));
const flag = (g) => Object.values(g).some((r) => r.tier >= 2 && (r.ready >= 0.5 || r.uptime >= 0.6) && (r.durRaw ?? 0) >= 2);
const order = (a, b) => Math.max(...Object.values(b[1]).map((r) => r.uptime)) - Math.max(...Object.values(a[1]).map((r) => r.uptime));
function table(cls, title) {
  const L = lasting.filter(([k]) => k.endsWith('|' + cls)).sort(order);
  if (!L.length) return '';
  let s = `\n#### ${title}\n\n| | Hero | Ability | What lasts (as the code calls it) | Tier I | Tier II | Tier III |\n|---|---|---|---|---|---|---|\n`;
  for (const [k, g] of L) { const r0 = Object.values(g)[0]; s += `| ${flag(g) ? '**!**' : ''} | ${name(r0.hero)} | ${abn(r0.hero, r0.ab)} | ${what(r0)} | ${cell(g[1])} | ${cell(g[2])} | ${cell(g[3])} |\n`; }
  return s;
}
let out = `<!-- generated by tools/audit/cooldowns/report.mjs from ${fights} fights -->\n`;
out += table('state', 'On the hero himself: a form, a stance, a mount, a channel, a buff');
out += table('ally', 'On friends: buffs, heals over time, rays');
out += table('summon', 'Summons and pets');
out += table('zone', 'In the world: zones, walls, traps, thrown things that stay');
// the proposals
if (cmp.length) {
  const sg = (x) => (x == null || !isFinite(x) ? '-' : (x >= 0 ? '+' : '') + Math.round(100 * x) + '%');
  out += `\n#### The proposals, measured\n\n| Hero | Ability | Tier | Uptime today | a) starts at the end | b) + average length | c) half left at the end | Damage a second, a / b / c | Wins today / a / b / c |\n|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of cmp) {
    const h = r.hero_, rel = (k) => (h.today && h[k] ? h[k].dps / h.today.dps - 1 : null);
    out += `| ${name(r.hero)} | ${abn(r.hero, r.ab)} | ${'I'.repeat(r.tier)} | ${pc(r.up.today)} | ${pc(r.up.a)} | ${pc(r.up.b)} | ${pc(r.up.c)} | ${sg(rel('a'))} / ${sg(rel('b'))} / ${sg(rel('c'))} | ${pc(h.today && h.today.win)} / ${pc(h.a && h.a.win)} / ${pc(h.b && h.b.win)} / ${pc(h.c && h.c.win)} |\n`;
  }
}
// cut short: effects that often end before their time
const short = rows.filter((r) => r.cls !== 'foe' && r.casts >= 15 && (r.durRaw ?? 0) >= 1.5 && (r.why.cc + r.why.down) / Math.max(1, r.why.end + r.why.cc + r.why.down + r.why.recast) >= 0.05);
if (short.length) {
  out += `\n#### Effects that often end early\n\n| Hero | Ability | Kind | Tier | Ends from a stun/freeze/sleep | Ends with the hero down | Its target dead by then | Median length | Cooldown left then |\n|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of short.sort((a, b) => (b.why.cc + b.why.down) - (a.why.cc + a.why.down))) { const n = Math.max(1, r.why.end + r.why.cc + r.why.down + r.why.recast);
    out += `| ${name(r.hero)} | ${abn(r.hero, r.ab)} | ${KIND[r.cls]} | ${'I'.repeat(r.tier)} | ${pc(r.why.cc / n)} | ${pc(r.why.down / n)} | ${pc(r.tgtDead)} | ${f1(r.dur)}s | ${f1(r.cdLeft)}s |\n`; }
}
process.stdout.write(out);
