for bid, title, text, why, pick, opts in B:
  items = []
  for i, (lab, line) in enumerate(opts, 1):
    p = f'design/r19-art/hitfx/{bid}/{bid}-{i}.mp4'
    if not os.path.exists(p): print('missing', p)
    items.append({'id': f'{bid}-{i}', 'label': f'{i} {lab}', 'video': V + f'{bid}/{bid}-{i}.mp4', 'text': line})
