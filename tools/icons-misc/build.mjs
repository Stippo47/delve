// Round 19, icons-misc lane: builds the round 19 icon sets from the drawings in this folder.
//   node tools/icons-misc/build.mjs          -> art/icons/{stats,trinkets,potions,ui}/*.svg (B and soft in subfolders),
//                                               js/icons-r19.js (the same, as strings, for icons.js), and the pages for
//                                               the set sheets in tools/icons-misc/pages/
//   node tools/icons-misc/build.mjs --snap   -> also renders those pages to design/r19-icons/misc/ (headless Edge)
// The drawing kit is round 14's (design/icons-r14/kit.mjs, parts.mjs); nothing here is loaded by the game.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url'; import { execFileSync } from 'node:child_process';
import { Ctx } from '../../design/icons-r14/kit.mjs';
import { STAT_A, STAT_B, STAT_NAMES, STAT_ALIAS } from './stats.mjs';
import { TRINKET_DRAW, POTION_DRAW, render, TREATMENTS } from './trinkets.mjs';
import { UI_DRAW, UI_NAMES } from './ui.mjs';
import { inline, page } from './sheets.mjs';
const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, '../..');
const { TRINKETS } = await import('../../js/trinkets.js');
const { POTIONS } = await import('../../js/potions.js');
const RARITY = { common: '#8F97A3', rare: '#3E8FC7', epic: '#9B5BC9', legendary: '#D9822B' }; // js/progress.js

// ------------------------------------------------------------------------------------------------ the sets
const tFn = (D, tr) => Object.fromEntries(Object.entries(D).map(([id, d]) => [id, (c) => render(c, d(c), tr)]));
export const SETS = {
  statsA: { dir: 'stats', fns: STAT_A },
  statsB: { dir: 'stats/b', fns: STAT_B },
  trinkets: { dir: 'trinkets', fns: tFn(TRINKET_DRAW, 'paint') },
  trinketsSoft: { dir: 'trinkets/soft', fns: tFn(TRINKET_DRAW, 'soft') },
  potions: { dir: 'potions', fns: tFn(POTION_DRAW, 'paint') },
  potionsSoft: { dir: 'potions/soft', fns: tFn(POTION_DRAW, 'soft') },
  ui: { dir: 'ui', fns: tFn(UI_DRAW, 'paint') },
};
const missing = Object.keys(TRINKETS).filter((id) => !id.includes(':') && !TRINKET_DRAW[id]).concat(Object.keys(POTIONS).filter((id) => !POTION_DRAW[id]));
if (missing.length) console.log('NOT DRAWN:', missing.join(' '));

const svgOf = (fn, prefix) => { const c = new Ctx(prefix); return c.svg(fn(c)); };
const mod = {};
let bytes = 0;
for (const [key, S] of Object.entries(SETS)) {
  const dir = path.join(ROOT, 'art/icons', S.dir); fs.mkdirSync(dir, { recursive: true });
  for (const f of fs.readdirSync(dir)) if (f.endsWith('.svg')) fs.rmSync(path.join(dir, f));
  mod[key] = {};
  for (const [id, fn] of Object.entries(S.fns)) {
    if (key.startsWith('stats') && STAT_ALIAS[id]) continue; // the skill web's names for the same pictures: icons.js maps them
    fs.writeFileSync(path.join(dir, id + '.svg'), svgOf(fn, `${key}-${id}`) + '\n');
    // for the game: no xmlns or size (icons.js and CSS add what each place needs), ids made unique per use at run time
    const s = svgOf(fn, '@I').replace(' xmlns="http://www.w3.org/2000/svg"', '').replace(' width="64" height="64"', '');
    mod[key][id] = s; bytes += s.length;
  }
}
// two modules: what the game shows by default, and the alternatives behind the switch (loaded only when picked)
const MODS = { 'icons-r19.js': ['statsA', 'trinkets', 'potions', 'ui'], 'icons-r19-alt.js': ['statsB', 'trinketsSoft', 'potionsSoft'] };
for (const [file, keys] of Object.entries(MODS)) {
  const js = `// GENERATED by tools/icons-misc/build.mjs (round 19, icons-misc lane) from the drawings there: do not edit by hand.
// Round 19 icon sets as SVG strings in a 64x64 box. '@I' in an id is made unique each time icons.js hands one out.
${file === 'icons-r19.js' ? `//   statsA    painted emblem (design/icons-r14 style A): the stat icons the game shows by default
//   trinkets / potions   painted objects, no container      ui   the small UI pictures (gold, points, key, lock, notes)
// The alternatives (stats in style B, the soft paint trinkets and potions) are in icons-r19-alt.js.
export const R19 = {` : `//   statsB    bold glyph (style B)      trinketsSoft / potionsSoft   the lighter soft paint
// Loaded by icons.js only when one of them is picked (Settings, or ?icons=...).
export const R19_ALT = {`}
${keys.map((k) => `  ${k}: {\n${Object.entries(mod[k]).map(([id, s]) => `    ${id}: ${JSON.stringify(s)},`).join('\n')}\n  },`).join('\n')}
};
`;
  fs.writeFileSync(path.join(ROOT, 'js', file), js);
  console.log('js/' + file, Math.round(js.length / 1024), 'KB,', keys.reduce((a, k) => a + Object.keys(mod[k]).length, 0), 'icons');
}

// ------------------------------------------------------------------------------------------------ the sheets
const pages = path.join(HERE, 'pages'); fs.rmSync(pages, { recursive: true, force: true }); fs.mkdirSync(pages, { recursive: true });
const jobs = [];
const put = (name, html, w = 390, s = 3) => { fs.writeFileSync(path.join(pages, name + '.html'), html); jobs.push([name, w, s]); };
const ic = (fn, px) => inline(fn, px);
const VAL = { hp: '180', armor: '6', dmg: '24', aps: '1.40', speed: '92', range: '240', cd: '7.5s', haste: '+8%', heal: '+12%', potency: '+15%', regen: '3%', crit: '×2', kills: '96',
  runs: '9', taken: '5,120', blocked: '1,840', downs: '2', revives: '3', best: '61', xp: '530', gold: '1,240', found: '3', elite: '5', major: '1', tier: 'II', fill: '100', decay: '8',
  time: '4:20', bag: '2', floor: '3 / 3', mastery: '1/1', abDmg: '+24%', abCd: '-12%', abHeal: '+30%', abStatus: '+40%' };
const GAME_STATS = ['hp', 'armor', 'speed', 'dmg', 'aps', 'range', 'cd', 'haste', 'heal', 'potency', 'kills', 'runs', 'taken', 'blocked', 'downs', 'revives', 'best', 'xp', 'gold', 'found', 'elite', 'major', 'tier', 'fill', 'decay', 'time', 'bag', 'floor'];
const WEB = ['abDmg', 'abCd', 'abHeal', 'abStatus', 'mastery', 'regen', 'crit'];
function statSheet(key, title, line) {
  const S = SETS[key].fns;
  const cell = (id) => `<div class="cell">${ic(S[id], 50)}<div class="n">${STAT_NAMES[id]}</div></div>`;
  const chip = (id, px, fs) => `<span class="chip" style="font-size:${fs}px">${ic(S[id], px)}<span>${VAL[id]}</span></span>`;
  return page(`<h1>${title}</h1><div class="sub">${line}</div>
    <div class="cap" style="margin-top:12px">Every stat the game shows (icons.js statIcon)</div>
    <div class="grid" style="grid-template-columns:repeat(7,1fr)">${GAME_STATS.map(cell).join('')}</div>
    <div class="cap" style="margin-top:12px">The skill web's ability nodes and mastery tips, and two spares (regen, critical)</div>
    <div class="grid" style="grid-template-columns:repeat(7,1fr)">${WEB.map(cell).join('')}</div>
    <div class="panel"><div class="cap">Beside a number, 20 px (the stats page's ability rows)</div><div class="row" style="margin-top:8px;font-size:16px">${GAME_STATS.slice(0, 12).map((id) => chip(id, 20, 16)).join('')}</div></div>
    <div class="panel"><div class="cap">14 px, the smallest anyone should use</div><div class="row" style="margin-top:8px">${GAME_STATS.map((id) => chip(id, 14, 12)).join('')}</div></div>`);
}
put('stats-a', statSheet('statsA', 'Stats · A · Painted emblem', 'Default now. The object itself, outlined and shaded, no tile. Speed lines mean "faster" (attack speed, move speed, ability haste).'));
put('stats-b', statSheet('statsB', 'Stats · B · Bold glyph', 'Behind the switch (Settings → Stat icons, or ?icons=b). One flat colour per stat, the same ink outline.'));

function trinketSheet(tr) {
  const T = tFn(TRINKET_DRAW, tr), Pn = tFn(POTION_DRAW, tr), T2 = TREATMENTS[tr];
  const ids = Object.keys(TRINKETS).filter((id) => !id.includes(':'));
  const cell = (id) => { const t = TRINKETS[id]; return `<div class="cell">${ic(T[id], 54)}<div class="n" style="min-height:22px">${t.name}<br><span style="color:${RARITY[t.rarity]};font-size:8px;text-transform:capitalize">${t.rarity}</span></div></div>`; };
  const real = (px, pad, rad) => ids.map((id) => `<span class="tile" style="--rar:${RARITY[TRINKETS[id].rarity]};width:${px + pad * 2}px;height:${px + pad * 2}px;border-radius:${rad}px">${ic(T[id], px)}</span>`).join('');
  const floor = ids.map((id) => ic(T[id], 30)).join('');
  return page(`<h1>Trinkets · ${tr === 'paint' ? '1' : '2'} · ${T2.name}</h1><div class="sub">${T2.line}</div>
    <div class="grid" style="grid-template-columns:repeat(6,1fr);margin-top:12px">${ids.map(cell).join('')}</div>
    <div class="cap" style="margin-top:10px">Potions, the same way</div>
    <div class="grid" style="grid-template-columns:repeat(6,1fr)">${Object.keys(POTIONS).map((id) => `<div class="cell">${ic(Pn[id], 54)}<div class="n">${POTIONS[id].name}</div></div>`).join('')}</div>
    <div class="panel"><div class="cap">Real size: the trader's shelf (42 px in its rarity tile)</div><div class="row" style="gap:6px;margin-top:8px">${real(42, 7, 16)}</div></div>
    <div class="panel"><div class="cap">The battle card's 18 px and the inspect list's 28 px</div><div class="row" style="gap:3px;margin-top:8px">${ids.map((id) => ic(T[id], 18)).join('')}</div>
      <div class="row" style="gap:5px;margin-top:8px">${ids.map((id) => `<span class="tile" style="width:34px;height:34px;border-radius:10px;box-shadow:none">${ic(T[id], 28)}</span>`).join('')}</div></div>
    <div class="panel" style="background:linear-gradient(180deg,#8E8D96,#6E6A72);box-shadow:none"><div class="cap" style="color:#2B2230">Dropped on a dungeon floor</div><div class="row" style="gap:8px;margin-top:8px">${floor}</div></div>`);
}
put('trinkets-1-paint', trinketSheet('paint'));
put('trinkets-2-soft', trinketSheet('soft'));

const UIF = SETS.ui.fns;
put('ui', page(`<h1>Potions and UI icons</h1><div class="sub">The stand-in UI pictures as painted objects, no container (Settings → Trinket and potion icons, or ?icons=r19).</div>
  <div class="cap" style="margin-top:12px">Potions (painted)</div>
  <div class="grid" style="grid-template-columns:repeat(6,1fr)">${Object.keys(POTIONS).map((id) => `<div class="cell">${ic(SETS.potions.fns[id], 54)}<div class="n">${POTIONS[id].name}</div></div>`).join('')}</div>
  <div class="cap" style="margin-top:10px">UI</div>
  <div class="grid" style="grid-template-columns:repeat(5,1fr)">${Object.keys(UI_DRAW).map((id) => `<div class="cell">${ic(UIF[id], 54)}<div class="n">${UI_NAMES[id]}</div></div>`).join('')}</div>
  <div class="panel"><div class="cap">Real size: prices, points, notes</div>
    <div class="row" style="margin-top:8px;font-size:15px"><span class="chip">${ic(UIF.coin, 15)}1,240</span><span class="chip" style="color:#4FD8C8">${ic(UIF.points, 15)}3</span><span class="chip">${ic(UIF.key, 16)}2</span><span class="chip">${ic(UIF.lock, 16)}Level 5</span><span class="chip">${ic(UIF.flask, 18)}Potions</span></div>
    <div class="row" style="margin-top:10px;font-size:13px"><span class="chip">${ic(UIF.door, 18)}The Warren is open</span><span class="chip">${ic(UIF.flag, 18)}Checkpoint: floor 3</span><span class="chip">${ic(UIF.trader, 18)}New wares at the trader</span></div></div>`));

for (const [k, S] of [['statsA', 'a'], ['statsB', 'b']]) put(`thumb-stats-${S}`, page(`<div style="display:grid;grid-template-columns:repeat(3,1fr);gap:14px;place-items:center;width:336px;height:336px">${['hp', 'dmg', 'armor', 'aps', 'speed', 'range', 'cd', 'heal', 'kills'].map((id) => ic(SETS[k].fns[id], 92)).join('')}</div>`, 360), 360, 2);

fs.writeFileSync(path.join(pages, 'jobs.json'), JSON.stringify(jobs));
if (process.argv.includes('--snap')) {
  const out = path.join(ROOT, 'design/r19-icons/misc'); fs.mkdirSync(out, { recursive: true });
  const args = jobs.flatMap(([n, w, s]) => [path.join(pages, n + '.html'), path.join(out, `set-${n}.png`), String(w), String(s)]);
  execFileSync('node', [path.join(HERE, 'snap.mjs'), ...args], { stdio: 'inherit' });
}
