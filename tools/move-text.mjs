// The Book's words for every elite move (round 13): read from the comments the code already has above (or beside) each
// ELITES entry, so nobody writes them twice. Writes js/movetext.js. Run again after adding enemies:
//   node tools/move-text.mjs
// An entry whose comment says it has no move ("none") is written as '' (the Book shows no elite move for it); a kind with an elite move but no comment gets the
// Book's fallback line.
import fs from 'node:fs';
import path from 'node:path';

const dir = 'js', out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.js'))) {
  const lines = fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/);
  let inside = false, depth = 0;
  for (let i = 0; i < lines.length; i++) {
    const L = lines[i];
    if (!inside) { if (/^export const ELITES = \{|^Object\.assign\(ELITES, \{/.test(L)) { inside = true; depth = 1; } continue; }
    const m = L.match(/^ {2}(\w+): \{/);
    if (m && depth === 1) {
      let text = '';
      const tail = L.match(/\}\s*\},?\s*\/\/\s*(.+)$/) || L.match(/\/\/\s*(.+)$/);
      if (tail && /\}\s*\}?,?\s*\/\//.test(L)) text = tail[1];
      const opens = L.match(/\{\s*\/\/\s*(.+)$/); if (!text && opens) text = opens[1]; // name: { tick(w, u, dt) { // what it does
      if (!text) { // the comment block right above
        const above = []; for (let j = i - 1; j >= 0 && /^\s*\/\//.test(lines[j]); j--) above.unshift(lines[j].replace(/^\s*\/\/\s?/, ''));
        text = above.join(' ');
      }
      text = clean(text);
      if (text != null) out[m[1]] = text; // '' = it says it has none
    }
    for (const ch of L.replace(/'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`|"(?:[^"\\]|\\.)*"|\/\/.*$/g, '')) { if (ch === '{') depth++; else if (ch === '}') depth--; }
    if (depth <= 0) inside = false;
  }
}
function clean(t) {
  t = t.replace(/\([^)]*\)/g, '').replace(/\s+/g, ' ').replace(/ ([.,;:])/g, '$1').trim();
  const c = t.match(/^([A-Z][\w' -]{0,30}):\s+(.*)$/); // "Rat: plague-ridden; ..." -> "plague-ridden; ..."
  if (c && c[1].split(' ').length <= 4) t = c[2];
  if (!t || /^none\b/i.test(t) || /^-+$/.test(t)) return '';
  t = t[0].toUpperCase() + t.slice(1);
  if (!/[.!?]$/.test(t)) t += '.';
  return t;
}
const keys = Object.keys(out).sort();
const body = keys.map((k) => `  ${k}: ${JSON.stringify(out[k])},`).join('\n');
fs.writeFileSync(path.join(dir, 'movetext.js'), `// Generated by tools/move-text.mjs from the comments on each ELITES entry: what an elite of a kind does on top of its
// kit, in the Book (round 13). Don't edit by hand; fix the comment and run the tool again.
export const ELITE_MOVE = {
${body}
};
`);
console.log(keys.length, 'elite moves written to js/movetext.js');
